//go:build ignore

// Generate the platform-name graphic ranges used by the TypeScript Gateway
// descriptor snapshot reader. Source: Go's unicode package, Unicode 15.0.0,
// as used by Gateway commit 17168fc11cac3a9f4947564dfb65b2f239827681
// (validPlatformName in go/engine.go). Run with the pinned Go toolchain:
// go run scripts/descriptor-graphic-ranges.go packages/harness/descriptorGraphicRanges.json go/context/descriptor_graphic_ranges.go
package main

import (
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"strings"
	"unicode"
)

func main() {
	if unicode.Version != "15.0.0" || len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "requires Unicode 15.0.0 and TypeScript/Go output filenames")
		os.Exit(1)
	}
	ranges := [][2]uint32{}
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if !unicode.IsGraphic(r) {
			continue
		}
		if len(ranges) > 0 && uint32(r) == ranges[len(ranges)-1][1]+1 {
			ranges[len(ranges)-1][1] = uint32(r)
		} else {
			ranges = append(ranges, [2]uint32{uint32(r), uint32(r)})
		}
	}
	data, err := json.Marshal(ranges)
	if err == nil {
		err = os.WriteFile(os.Args[1], append(data, '\n'), 0644)
	}
	if err == nil {
		var goText strings.Builder
		goText.WriteString("// Code generated by scripts/descriptor-graphic-ranges.go from Unicode 15.0.0; DO NOT EDIT.\npackage runcontext\n\nvar descriptorGraphicRanges = [...][2]rune{\n")
		for _, r := range ranges {
			fmt.Fprintf(&goText, "{%d,%d},\n", r[0], r[1])
		}
		goText.WriteString("}\n")
		var source []byte
		source, err = format.Source([]byte(goText.String()))
		if err == nil {
			err = os.WriteFile(os.Args[2], source, 0644)
		}
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
